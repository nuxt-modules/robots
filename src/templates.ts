import type { NitroRuntimeCompatibility } from 'nuxtseo-shared/kit'
import { addTypeTemplate } from '@nuxt/kit'
import { renderNitroTypeAugmentations } from 'nuxtseo-shared/kit'

interface TemplateContext {
  nitroCompatibility: NitroRuntimeCompatibility
}

export function registerTypeTemplates({ nitroCompatibility }: TemplateContext) {
  // Nuxt-only type augmentations (PageMeta)
  addTypeTemplate({
    filename: 'types/nuxt-robots-nuxt.d.ts',
    getContents: () => `// Generated by nuxt-robots
import type { RobotsValue } from '@nuxtjs/robots'

declare module '#app' {
  interface PageMeta {
    robots?: RobotsValue
  }
}

export {}
`,
  }, {
    nuxt: true,
  })

  const routeRules = `robots?: RobotsValue | {
  indexable: boolean
  rule: string
}`
  const runtimeHooks = `'robots:config': (ctx: HookRobotsConfigContext<${nitroCompatibility.eventType}>) => void | Promise<void>
'robots:robots-txt': (ctx: HookRobotsTxtContext<${nitroCompatibility.eventType}>) => void | Promise<void>`
  const nitroTypes = renderNitroTypeAugmentations(nitroCompatibility, {
    eventContext: `robots: RobotsContext
robotsProduction?: RobotsContext`,
    nitroInterfaces: {
      NitroApp: `_robots: {
  ctx: HookRobotsConfigContext<${nitroCompatibility.eventType}>
  nuxtContentUrls?: Set<string>
},
_robotsRuleMatcher: (url: string) => any
_robotsPatternMap?: Map<string, PatternMapValue>`,
    },
    routeConfig: routeRules,
    routeRules,
    runtimeHooks,
  })

  // Nitro type augmentations (NitroApp, NitroRouteRules, NitroRouteConfig, NitroRuntimeHooks, H3EventContext)
  addTypeTemplate({
    filename: 'types/nuxt-robots-nitro.d.ts',
    getContents: () => `// Generated by nuxt-robots
import type { HookRobotsConfigContext, HookRobotsTxtContext, RobotsValue, RobotsContext, PatternMapValue } from '@nuxtjs/robots'

${nitroTypes}

export {}
`,
  }, {
    nitro: true,
    node: true,
    nuxt: true,
  })
}
